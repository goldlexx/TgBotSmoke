const pools=[
  ['co','teeth','pulse','taste','sleep','smoke'],
  ['breath','smell','activity','vessels','energy'],
  ['nails','cough','gums','heart','coronary','lung','bladder','asthma']
];
export function dailyFact(seconds,localDay,id) {
  const pool=pools[seconds>=30*day?2:seconds>=7*day?1:0];
  const index=Math.floor(Date.parse(localDay)/86400000)+719163+id;
  return pool[((index%pool.length)+pool.length)%pool.length];
}

export const currentStage=seconds=>stages.findLastIndex(([at])=>seconds>=at);
export const healthNote='Темп восстановления индивидуален. Этапы отражают срок без сигарет, а не состояние организма.';
export const generalSources=`<a href="${WHO}">ВОЗ · Польза отказа</a>\n<a href="${NHS}">NHS · Этапы восстановления</a>\n<a href="${CDC}">CDC · Долгосрочные изменения</a>`;
export const stageCards=(index,limit)=>stages[index][3].slice(0,limit).map(key=>{
  const [label,text]=healthCards[key];
  return `<b>${label}</b>\n${text}`;
});
export function healthReport(seconds,duration) {
  const index=currentStage(seconds),stage=stages[index],next=stages[index+1];
  return ['🫁 <b>Восстановление организма</b>',`<b>${duration} без сигарет</b>`,
    ...(index===3?[`Идёт ${Math.floor(seconds/(7*day))+1}-я неделя твоего пути.`]:[]),
    `📍 <b>Текущий период · ${stage?.[1]??'Первые минуты'}</b>`,...(stage?stageCards(index,3):[]),
    ...(next?[`🔭 <b>Ближайший ориентир · ${next[1]}</b>\n${next[2]}`]:[]),healthNote].join('\n\n');
}
