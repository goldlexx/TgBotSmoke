export function dailyFact(seconds,localDay,id) {
  const [,pool]=facts.findLast(([from])=>seconds>=from*day);
  const index=Math.floor(Date.parse(localDay)/86400000)+719163+id;
  return pool[index%pool.length];
}

export function healthReport(seconds,all=false) {
  const reached=stages.filter(([at])=>seconds>=at);
  const next=stages.filter(([at])=>seconds<at).slice(0,3);
  const line=([,period,fact,url])=>`${period} — ${fact} <a href="${url}">Источник</a>`;
  return [
    all?'<b>✅ Все достигнутые изменения</b>':'<b>🫁 Восстановление организма</b>',
    'Ориентиры для текущей серии. Сроки индивидуальны.',
    '',
    ...(reached.length?(all?reached:reached.slice(-2).reverse()).map(s=>'✅ '+line(s)):['Первые изменения ещё впереди.']),
    ...(!all?['','<b>🎯 Следующие изменения</b>',...(next.length?next.map(s=>'✨ '+line(s)):['Все ориентиры пройдены.'])]:[])
  ].join('\n');
}
